const desktop = join(dirname(fileURLToPath(import.meta.url)), "..");
const lucide = join(desktop, "..", "kai-ui-web", "node_modules", "lucide-react");
const assets = join(desktop, "assets", "icons");
mkdirSync(assets, { recursive: true });
mkdirSync(join(desktop, "src", "icons"), { recursive: true });

function iconData(name) {
  const source = readFileSync(join(lucide, "dist", "esm", "icons", `${name}.mjs`), "utf8");
  const alias = source.match(/export \{ default \} from '\.\/([\w-]+)\.mjs'/);
  if (alias) {
    return iconData(alias[1]);
  }
  const match = source.match(/const __iconData = (\{[\s\S]*?\n\});/);
  if (!match) {
    throw new Error(`no __iconData in ${name}.mjs`);
  }
  return new Function(`return ${match[1]};`)();
}

function escape(value) {
  return String(value).replaceAll("&", "&amp;").replaceAll('"', "&quot;").replaceAll("<", "&lt;");
}

function element([tag, attrs]) {
  const pairs = Object.entries(attrs)
    .filter(([key]) => key !== "key")
    .map(([key, value]) => `${key}="${escape(value)}"`);
  return `<${tag} ${pairs.join(" ")}/>`;
}

function pascal(name) {
  return name
    .split("-")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");
}

const variants = [];
for (const name of ICONS) {
  const data = iconData(name);
  if (data.size !== 24) {
    throw new Error(`${name}: expected a 24x24 icon, got ${data.size}`);
  }
  writeFileSync(join(assets, `${name}.svg`), `${data.node.map(element).join("\n")}\n`);
  variants.push({ name, ident: pascal(name) });
}
copyFileSync(join(lucide, "LICENSE"), join(assets, "LICENSE"));

const rust = `// @generated by scripts/gen-icons.mjs from lucide-react (ISC, see
// assets/icons/LICENSE). Do not edit by hand.

/// Lucide icons available to the desktop renderer (24x24, stroke based).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Icon {
${variants.map((v) => `    ${v.ident},`).join("\n")}
}

impl Icon {
    pub const ALL: &[Icon] = &[
${variants.map((v) => `        Icon::${v.ident},`).join("\n")}
    ];

    /// Lucide name, e.g. \`"eye-off"\`.
    pub fn name(self) -> &'static str {
        match self {
${variants.map((v) => `            Icon::${v.ident} => "${v.name}",`).join("\n")}
        }
    }

    pub fn from_name(name: &str) -> Option<Self> {
        Self::ALL.iter().copied().find(|icon| icon.name() == name)
    }

    /// SVG child elements in a 24x24 view box.
    pub fn body(self) -> &'static str {
        match self {
${variants
  .map((v) => `            Icon::${v.ident} => include_str!("../../assets/icons/${v.name}.svg"),`)
  .join("\n")}
        }
    }
}
`;
writeFileSync(join(desktop, "src", "icons", "catalog.rs"), rust);
console.log(`${variants.length} icons written`);
