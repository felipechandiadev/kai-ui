#[cfg(test)]
mod tests {
    use super::{HISTORY_LIMIT, Navigate, Route, Router};

    #[derive(Clone, Debug, PartialEq, Eq)]
    enum Page {
        Customers,
        Customer { id: u32 },
        Sales,
    }

    impl Route for Page {
        fn parse(path: &str) -> Option<Self> {
            let segments: Vec<&str> = path.trim_matches('/').split('/').collect();
            match segments.as_slice() {
                ["customers"] => Some(Self::Customers),
                ["customers", id] => id.parse().ok().map(|id| Self::Customer { id }),
                ["sales"] => Some(Self::Sales),
                _ => None,
            }
        }

        fn path(&self) -> String {
            match self {
                Self::Customers => "/customers".into(),
                Self::Customer { id } => format!("/customers/{id}"),
                Self::Sales => "/sales".into(),
            }
        }

        fn parent(&self) -> Option<Self> {
            match self {
                Self::Customer { .. } => Some(Self::Customers),
                _ => None,
            }
        }
    }

    #[test]
    fn paths_round_trip() {
        for page in [Page::Customers, Page::Customer { id: 42 }, Page::Sales] {
            assert_eq!(Page::parse(&page.path()), Some(page));
        }
        assert_eq!(Page::parse("/customers/ana"), None);
        assert_eq!(Page::parse("/nowhere"), None);
    }

    #[test]
    fn back_and_forward_walk_the_history() {
        let mut router = Router::new(Page::Customers);
        assert!(!router.can_go_back());
        assert!(router.push(Page::Customer { id: 1 }));
        assert!(router.push(Page::Sales));
        assert!(router.back());
        assert_eq!(router.current(), &Page::Customer { id: 1 });
        assert!(router.can_go_forward());
        assert!(router.forward());
        assert_eq!(router.current(), &Page::Sales);
        assert!(!router.forward());

        // A new route clears "forward".
        router.back();
        router.push(Page::Customers);
        assert!(!router.can_go_forward());
        // Going where you are is no entry.
        assert!(!router.push(Page::Customers));
    }

    #[test]
    fn up_goes_to_the_parent_as_a_new_entry() {
        let mut router = Router::new(Page::Customer { id: 7 });
        assert!(router.can_go_up());
        assert!(router.up());
        assert_eq!(router.current(), &Page::Customers);
        assert!(!router.can_go_up());
        assert!(router.back());
        assert_eq!(router.current(), &Page::Customer { id: 7 });
    }

    #[test]
    fn requests_by_path_ignore_unknown_paths() {
        let mut router = Router::new(Page::Customers);
        assert!(router.apply(Navigate::To("/customers/42".into())));
        assert_eq!(router.state().path, "/customers/42");
        assert!(!router.apply(Navigate::To("/nowhere".into())));
        assert_eq!(router.current(), &Page::Customer { id: 42 });
        assert!(router.apply(Navigate::Back));
        assert!(router.apply(Navigate::Forward));
        assert!(router.apply(Navigate::Up));
        assert_eq!(router.current(), &Page::Customers);
    }

    #[test]
    fn the_history_is_bounded() {
        let mut router = Router::new(Page::Customer { id: 0 });
        for id in 1..=HISTORY_LIMIT as u32 + 20 {
            router.push(Page::Customer { id });
        }
        let mut steps = 0;
        while router.back() {
            steps += 1;
        }
        assert_eq!(steps, HISTORY_LIMIT);
    }

    #[test]
    fn replace_leaves_no_entry() {
        let mut router = Router::new(Page::Customers);
        router.replace(Page::Sales);
        assert_eq!(router.current(), &Page::Sales);
        assert!(!router.can_go_back());
    }
}
