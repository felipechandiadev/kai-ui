/// A place in the app. Written by hand or generated by `kai-build`.
pub trait Route: Clone + Eq + fmt::Debug + 'static {
    /// `"/customers/42"` → the route; `None` when no route matches.
    fn parse(path: &str) -> Option<Self>;
    /// The inverse of [`Route::parse`]: `parse(&r.path()) == Some(r)`.
    fn path(&self) -> String;
    /// Where "up" goes (a detail → its list). Default: nowhere.
    fn parent(&self) -> Option<Self> {
        None
    }
}

/// A navigation request, from a click, a shortcut, a script or an agent.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum Navigate {
    Back,
    Forward,
    Up,
    /// To the route whose path this is; an unknown path changes nothing
    /// (`kai.navigate` rejects it before).
    To(String),
}

/// What the commands need to know about the history right now.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct NavState {
    pub path: String,
    pub can_go_back: bool,
    pub can_go_forward: bool,
    pub can_go_up: bool,
}

/// Most entries kept behind the current route; older ones are dropped.
pub const HISTORY_LIMIT: usize = 100;

/// Current route and history: plain data, tested without a window.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Router<R: Route> {
    back: Vec<R>,
    current: R,
    forward: Vec<R>,
}

impl<R: Route> Router<R> {
    pub fn new(start: R) -> Self {
        Self {
            back: Vec::new(),
            current: start,
            forward: Vec::new(),
        }
    }

    pub fn current(&self) -> &R {
        &self.current
    }

    /// Go to `route`, which becomes a history entry. Going where you are
    /// does nothing; it clears what "forward" had.
    pub fn push(&mut self, route: R) -> bool {
        if route == self.current {
            return false;
        }
        let previous = std::mem::replace(&mut self.current, route);
        self.back.push(previous);
        if self.back.len() > HISTORY_LIMIT {
            self.back.remove(0);
        }
        self.forward.clear();
        true
    }

    /// Show `route` in place of the current one, without a history entry
    /// (a redirect, a filter in the path).
    pub fn replace(&mut self, route: R) {
        self.current = route;
    }

    pub fn back(&mut self) -> bool {
        let Some(previous) = self.back.pop() else {
            return false;
        };
        let current = std::mem::replace(&mut self.current, previous);
        self.forward.push(current);
        true
    }

    pub fn forward(&mut self) -> bool {
        let Some(next) = self.forward.pop() else {
            return false;
        };
        let current = std::mem::replace(&mut self.current, next);
        self.back.push(current);
        true
    }

    /// Go to the parent of the current route, as a new history entry.
    pub fn up(&mut self) -> bool {
        match self.current.parent() {
            Some(parent) => self.push(parent),
            None => false,
        }
    }

    pub fn can_go_back(&self) -> bool {
        !self.back.is_empty()
    }

    pub fn can_go_forward(&self) -> bool {
        !self.forward.is_empty()
    }

    pub fn can_go_up(&self) -> bool {
        self.current.parent().is_some()
    }

    /// Carry out `request`; whether the route changed.
    pub fn apply(&mut self, request: Navigate) -> bool {
        match request {
            Navigate::Back => self.back(),
            Navigate::Forward => self.forward(),
            Navigate::Up => self.up(),
            Navigate::To(path) => R::parse(&path).is_some_and(|route| self.push(route)),
        }
    }

    pub fn state(&self) -> NavState {
        NavState {
            path: self.current.path(),
            can_go_back: self.can_go_back(),
            can_go_forward: self.can_go_forward(),
            can_go_up: self.can_go_up(),
        }
    }
}

/// An app with routes: what its navigation commands read and send.
pub trait Navigable: App {
    fn nav_state(&self) -> NavState;
    /// Whether `path` is a route of the app (usually
    /// `Route::parse(path).is_some()`); `kai.navigate` rejects the rest.
    fn has_route(path: &str) -> bool;
    /// The app's message that carries out `request` (usually
    /// `Msg::Navigate(request)`, applied with [`Router::apply`]).
    fn navigate(request: Navigate) -> Self::Msg;
}

/// An app whose sidebar collapses to a rail of icons
