//! Typed routes and history (docs/dev/26-router-y-kai-build.md §3).
//!
//! A [`Route`] is a place in the app with a stable text form (`path`). A
//! [`Router`] keeps the current route and the back/forward history; it is
//! plain data in the app's model, changed by messages like the rest. An
//! app that implements [`Navigable`] and calls
//! [`CommandRegistry::navigation`](crate::commands::CommandRegistry::navigation)
//! gets `kai.back` (⌘[), `kai.forward` (⌘]), `kai.up` (⌘↑) and
//! `kai.navigate`, and the session keeps scroll and focus per route
//! ([`App::route`]).
//!
//! ```ignore
//! #[derive(Clone, Debug, PartialEq, Eq)]
//! enum Page { Customers, Customer { id: u32 } }
//!
//! impl Route for Page {
//!     fn parse(path: &str) -> Option<Self> { /* "/customers/42" → Customer { id: 42 } */ }
//!     fn path(&self) -> String { /* the inverse */ }
//!     fn parent(&self) -> Option<Self> { /* Customer → Customers */ }
//! }
//!
//! // In update:
//! Msg::Navigate(to) => { self.router.apply(to); }
//! ```

