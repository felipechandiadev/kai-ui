/// A page: a small app with its own message type, the parameters of its
/// route and access to the state the whole app shares. A root (written by
/// hand or generated by `kai-build`) keeps the live pages and converts
/// their messages with [`Element::map`](crate::element::Element::map) and
/// [`Effects::map`].
pub trait Page: Sized + 'static {
    type Msg: Clone + fmt::Debug + 'static;
    /// What the route carries: `()` for `/customers`, an id for
    /// `/customers/:id`.
    type Params: Clone + Eq + 'static;
    /// State the whole app shares (session, loaded data).
    type State: 'static;

    fn init(params: &Self::Params, state: &Self::State) -> (Self, Effects<Self::Msg>);
    fn update(&mut self, msg: Self::Msg, cx: &mut Context<'_, Self::State>) -> Effects<Self::Msg>;
    fn view(&self, state: &Self::State) -> Element<Self::Msg>;
    /// User-visible title (window title, breadcrumbs); may be Spanish.
    fn title(&self, state: &Self::State) -> String;

    /// What the page shows over the whole window while it is on screen,
    /// such as a modal [`Dialog`](crate::components::Dialog): the root
    /// draws it as its last layer. A page's own view covers only the
    /// page's area. Default: nothing.
    fn overlay(&self, _state: &Self::State) -> Option<Element<Self::Msg>> {
        None
    }

    /// The theme of the whole window while the page is on screen, as
    /// [`App::theme`]. Default: the app's.
    fn theme(&self, _state: &Self::State) -> Option<crate::theme::Theme> {
        None
    }

    /// The window's background effect while the page is on screen, as
    /// [`App::background`]. Default: none.
    fn background(&self, _state: &Self::State) -> crate::background::BackgroundEffect {
        crate::background::BackgroundEffect::NONE
    }

    /// The page's commands, with
    /// [`CommandRegistry::page_action`](crate::commands::CommandRegistry::page_action).
    /// The root calls it once, from its own `App::commands`.
    fn commands<A: HasPage<Self>>(_registry: &mut crate::commands::CommandRegistry<A>) {}
}

/// A root that holds page `P` (the one `kai-build` generates does): what
/// the page's commands read and send.
pub trait HasPage<P: Page>: App {
    /// The page, while it is open.
    fn page(&self) -> Option<&P>;
    /// The state every page shares, for the page's queries.
    fn page_state(&self) -> &P::State;
    /// The root's message that carries `msg` to the page.
    fn page_msg(msg: P::Msg) -> Self::Msg;
}

/// What a page can do beyond its own model: change the shared state, ask
/// to navigate and show toasts. The root carries out the requests after
/// `update`.
pub struct Context<'a, S> {
    state: &'a mut S,
    requests: Vec<Navigate>,
    toasts: Vec<Toast<Infallible>>,
    /// Toasts with an action button, whose message is the page's: the
    /// root takes them with [`Context::take_action_toasts`].
    action_toasts: Vec<Box<dyn Any>>,
}

impl<'a, S> Context<'a, S> {
    pub fn new(state: &'a mut S) -> Self {
        Self {
            state,
            requests: Vec::new(),
            toasts: Vec::new(),
            action_toasts: Vec::new(),
        }
    }

    pub fn state(&mut self) -> &mut S {
        self.state
    }

    /// Go to the route of `path` after this update.
    pub fn navigate(&mut self, path: impl Into<String>) {
        self.requests.push(Navigate::To(path.into()));
    }

    pub fn back(&mut self) {
        self.requests.push(Navigate::Back);
    }

    /// Show `toast` in the root's stack, over the bottom right corner;
    /// it closes on its own unless it is an error. Its `id` is the root's
    /// to choose, and it has no action button (`Infallible`).
    pub fn toast(&mut self, toast: Toast<Infallible>) {
        self.toasts.push(toast);
    }

    /// [`Context::toast`] with an action button («Reintentar»): its
    /// message, of type `M`, goes to the page that showed it.
    pub fn toast_with_action<M: 'static>(&mut self, toast: Toast<M>) {
        self.action_toasts.push(Box::new(toast));
    }

    /// The toasts with an action that a page with messages `M` asked for;
    /// the root calls it right after that page's `update`.
    pub fn take_action_toasts<M: 'static>(&mut self) -> Vec<Toast<M>> {
        std::mem::take(&mut self.action_toasts)
            .into_iter()
            .filter_map(|toast| toast.downcast::<Toast<M>>().ok().map(|toast| *toast))
            .collect()
    }

    /// The navigation the page asked for, in order.
    pub fn into_requests(self) -> Vec<Navigate> {
        self.requests
    }

    /// The navigation and the toasts the page asked for, in order.
    pub fn into_parts(self) -> (Vec<Navigate>, Vec<Toast<Infallible>>) {
        (self.requests, self.toasts)
    }
}

/// A live region, invisible and out of the way of the pointer, that
/// announces the title of the page on screen: when the title changes
/// (the route changed) VoiceOver reads it. The root draws it once, next
/// to the page.
pub fn announcer<Msg>(title: &str) -> Element<Msg> {
    text(title)
        .role(Role::Status)
        .test_id("announcer")
        .class("absolute w-[1px] h-[1px] overflow-hidden pointer-events-none")
}

/// How a section shows in the sidebar. A `const` in each section's
/// `section.rs`; `title` and `group` are user-visible text.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct SectionMeta {
    pub title: &'static str,
    pub icon: Icon,
    /// Place in the sidebar; ties keep the order given.
    pub order: i32,
    /// Title of the sidebar group; `None` for the top, untitled group.
    pub group: Option<&'static str>,
}

/// The sidebar of a list of sections, sorted by [`SectionMeta::order`]
/// and grouped by [`SectionMeta::group`].
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SectionSidebar {
    pub groups: Vec<SidebarGroup>,
    /// Index into the given sections of each sidebar row, in row order.
    pub rows: Vec<usize>,
}

impl SectionSidebar {
    pub fn new(sections: &[SectionMeta]) -> Self {
        let mut order: Vec<usize> = (0..sections.len()).collect();
        order.sort_by_key(|&index| sections[index].order);
        // Groups appear where their first section does.
        let mut groups: Vec<(Option<&'static str>, Vec<usize>)> = Vec::new();
        for index in order {
            let group = sections[index].group;
            match groups.iter_mut().find(|(title, _)| *title == group) {
                Some((_, members)) => members.push(index),
                None => groups.push((group, vec![index])),
            }
        }
        let rows = groups
            .iter()
            .flat_map(|(_, members)| members.clone())
            .collect();
        let groups = groups
            .into_iter()
            .map(|(title, members)| {
                let items = members.into_iter().map(|index| {
                    SidebarItem::new(sections[index].title).icon(sections[index].icon)
                });
                match title {
                    Some(title) => SidebarGroup::titled(title, items),
                    None => SidebarGroup::untitled(items),
                }
            })
            .collect();
        Self { groups, rows }
    }

    /// Sidebar row of section `index`.
    pub fn row_of(&self, index: usize) -> Option<usize> {
        self.rows.iter().position(|&section| section == index)
    }

    /// Section shown in sidebar row `row`.
    pub fn section_at(&self, row: usize) -> Option<usize> {
        self.rows.get(row).copied()
    }
}

#[cfg(test)]
mod tests {
    use super::{HISTORY_LIMIT, Navigate, Route, Router, SectionMeta, SectionSidebar};
    use crate::icons::Icon;

    #[test]
    fn announcer_is_a_live_status_with_the_title() {
        let el = super::announcer::<()>("Clientes");
        assert_eq!(el.role, Some(crate::element::Role::Status));
        assert_eq!(el.text_content(), "Clientes");
    }

    #[derive(Clone, Debug, PartialEq, Eq)]
    enum Page {
        Customers,
        Customer { id: u32 },
        Sales,
    }

    impl Route for Page {
        fn parse(path: &str) -> Option<Self> {
            let segments: Vec<&str> = path.trim_matches('/').split('/').collect();
            match segments.as_slice() {
                ["customers"] => Some(Self::Customers),
                ["customers", id] => id.parse().ok().map(|id| Self::Customer { id }),
                ["sales"] => Some(Self::Sales),
                _ => None,
            }
        }

        fn path(&self) -> String {
            match self {
                Self::Customers => "/customers".into(),
                Self::Customer { id } => format!("/customers/{id}"),
                Self::Sales => "/sales".into(),
            }
        }

        fn parent(&self) -> Option<Self> {
            match self {
                Self::Customer { .. } => Some(Self::Customers),
                _ => None,
            }
        }
    }

    #[test]
    fn paths_round_trip() {
        for page in [Page::Customers, Page::Customer { id: 42 }, Page::Sales] {
            assert_eq!(Page::parse(&page.path()), Some(page));
        }
        assert_eq!(Page::parse("/customers/ana"), None);
        assert_eq!(Page::parse("/nowhere"), None);
    }

    #[test]
    fn back_and_forward_walk_the_history() {
        let mut router = Router::new(Page::Customers);
        assert!(!router.can_go_back());
        assert!(router.push(Page::Customer { id: 1 }));
        assert!(router.push(Page::Sales));
        assert!(router.back());
        assert_eq!(router.current(), &Page::Customer { id: 1 });
        assert!(router.can_go_forward());
        assert!(router.forward());
        assert_eq!(router.current(), &Page::Sales);
        assert!(!router.forward());

        // A new route clears "forward".
        router.back();
        router.push(Page::Customers);
        assert!(!router.can_go_forward());
        // Going where you are is no entry.
        assert!(!router.push(Page::Customers));
    }

    #[test]
    fn up_goes_to_the_parent_as_a_new_entry() {
        let mut router = Router::new(Page::Customer { id: 7 });
        assert!(router.can_go_up());
        assert!(router.up());
        assert_eq!(router.current(), &Page::Customers);
        assert!(!router.can_go_up());
        assert!(router.back());
        assert_eq!(router.current(), &Page::Customer { id: 7 });
    }

    #[test]
    fn requests_by_path_ignore_unknown_paths() {
        let mut router = Router::new(Page::Customers);
        assert!(router.apply(Navigate::To("/customers/42".into())));
        assert_eq!(router.state().path, "/customers/42");
        assert!(!router.apply(Navigate::To("/nowhere".into())));
        assert_eq!(router.current(), &Page::Customer { id: 42 });
        assert!(router.apply(Navigate::Back));
        assert!(router.apply(Navigate::Forward));
        assert!(router.apply(Navigate::Up));
        assert_eq!(router.current(), &Page::Customers);
    }

    #[test]
    fn the_history_is_bounded() {
        let mut router = Router::new(Page::Customer { id: 0 });
        for id in 1..=HISTORY_LIMIT as u32 + 20 {
            router.push(Page::Customer { id });
        }
        let mut steps = 0;
        while router.back() {
            steps += 1;
        }
        assert_eq!(steps, HISTORY_LIMIT);
    }

    #[test]
    fn replace_leaves_no_entry() {
        let mut router = Router::new(Page::Customers);
        router.replace(Page::Sales);
        assert_eq!(router.current(), &Page::Sales);
        assert!(!router.can_go_back());
    }

    #[test]
    fn the_sidebar_sorts_by_order_and_groups_by_title() {
        let meta = |title, order, group| SectionMeta {
            title,
            icon: Icon::House,
            order,
            group,
        };
        let sections = [
            meta("Ventas", 30, Some("Datos")),
            meta("Inicio", 0, None),
            meta("Clientes", 20, Some("Datos")),
            meta("Ajustes", 90, None),
        ];
        let sidebar = SectionSidebar::new(&sections);
        // Untitled group first (Inicio at 0), then «Datos» in order.
        assert_eq!(sidebar.rows, [1, 3, 2, 0]);
        assert_eq!(sidebar.groups.len(), 2);
        assert_eq!(sidebar.groups[1].items[0].label, "Clientes");
        assert_eq!(sidebar.row_of(0), Some(3));
        assert_eq!(sidebar.section_at(2), Some(2));
    }
}
